    #   처치및수술 컬럼 비공란만으로 수술로 굳던 오분류 제거. 부목·캐스트는 처치이지 수술 아님.
    #   ★ 진짜 정복술(관혈적정복·도수정복·고정술 등)은 강수술 신호가 있어 그대로 수술 유지된다.
    "부목", "캐스트", "깁스", "석고붕대", "스플린트", "STARFIX",
    # BOHUMFIT-106: 이학요법(물리치료) 계열 — '이학요법료/이학요법' 카테고리 행이 처치및수술
    #   컬럼 비공란만으로 수술로 굳던 오분류 제거(예: 한냉치료·냉동치료). 이학요법은 수술 아님.
    #   ★ 강수술 신호(정복·관혈·고정술·절제 등)가 있으면 그대로 수술 유지(진짜 수술 누락 0).
    #   주: 전부 풀 복합어로 substring 매칭 — '냉동수술/도수정복술' 등 진짜 수술명과 겹치지 않음.
