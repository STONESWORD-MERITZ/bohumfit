# -*- coding: utf-8 -*-
"""BOHUMFIT-286(B1) — 1~5종 수술비 tier 오검출 회귀.

★원문 근거(정본C 알파Plus 가입제안서 p10~11 실측 · 2026-08-11)
  상해 1~5종 = 20 / 30 / 100 / 500 / 1,000만원
  질병 1~5종 = 20 /  30 /  50 / 100 /   400만원
  수기표(`정본C 수기 비교분석표` 리모델링 r11~15 N·O열)도 같은 값이다.

★수정 전 실동작(재현 확인)
  10개 행이 **전부 `5종`으로 붕괴**했다. 상세면 서술이 "1-5종 수술분류표"로 시작해
  `([1-5])\\s*종\\s*수술` 정규식이 **범위 표기의 5**를 먼저 잡았기 때문이다.
  게다가 tier를 못 가리면 상해·질병 **양쪽에 같은 값**을 넣었고, `_entry`의 `merge_rule`
  기본값이 `AGG_REP`(큰 값 채택)라 두 행 모두 최댓값 1,000만원이 됐다.
  → 질병 5종이 400만원이 아니라 **1,000만원**으로 나갔다(설계사가 고객에게 안내하는 표다).

★이 파일이 고정하는 계약
  ①범위 표기(`1-5종`·`1~5종`)를 tier로 읽지 않는다
  ②상해/질병이 한쪽만 적힌 줄은 **그쪽으로만** 넣는다
  ③가입담보리스트의 대괄호 표기(`[상해3종]`)도 tier로 인정한다
"""
from __future__ import annotations

from coverage.proposal_parser import _extract_tier_surgery_entries

# 상세면 서술형 — 원문 문장 구조 그대로(금액만 원문값).
DETAIL_LINES = [
    "보험기간 중 상해로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 1종 수술을 받은 경우 20만원 274",
    "보험기간 중 상해로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 2종 수술을 받은 경우 30만원 453",
    "보험기간 중 상해로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 3종 수술을 받은 경우 1백만원 180",
    "보험기간 중 상해로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 4종 수술을 받은 경우 5백만원 33",
    "보험기간 중 상해로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 5종 수술을 받은 경우 1천만원 21",
    "보험기간 중 질병으로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 1종 수술을 받은 경 20만원 2,330",
    "보험기간 중 질병으로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 2종 수술을 받은 경 30만원 2,013",
    "보험기간 중 질병으로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 3종 수술을 받은 경 50만원 1,075",
    "보험기간 중 질병으로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 4종 수술을 받은 경 1백만원 150",
    "보험기간 중 질병으로 1-5종 수술분류표Ⅱ(약관참조)에서 정한 5종 수술을 받은 경 4백만원 7,760",
]

EXPECTED = {
    "N종수술비(상해 1종)": 200_000,
    "N종수술비(상해 2종)": 300_000,
    "N종수술비(상해 3종)": 1_000_000,
    "N종수술비(상해 4종)": 5_000_000,
    "N종수술비(상해 5종)": 10_000_000,
    "N종수술비(질병 1종)": 200_000,
    "N종수술비(질병 2종)": 300_000,
    "N종수술비(질병 3종)": 500_000,
    "N종수술비(질병 4종)": 1_000_000,
    "N종수술비(질병 5종)": 4_000_000,
}


def _by_name(lines) -> dict[str, int]:
    return {e["kb_name"]: e["amount"] for e in _extract_tier_surgery_entries(lines)}


def test_each_tier_keeps_its_own_amount():
    """★10개 종별이 각자 금액을 지킨다 — 수정 전에는 전부 5종·최댓값으로 붕괴했다."""
    assert _by_name(DETAIL_LINES) == EXPECTED


def test_range_literal_is_not_read_as_tier():
    """★`1-5종 수술분류표`의 5를 tier로 읽지 않는다(이 결함의 직접 원인)."""
    entries = _by_name(["보험기간 중 질병으로 1-5종 수술분류표Ⅱ에서 정한 2종 수술을 받은 경 30만원"])
    assert entries == {"N종수술비(질병 2종)": 300_000}
    assert "N종수술비(질병 5종)" not in entries


def test_single_kind_line_does_not_leak_to_the_other():
    """★상해 줄이 질병 행까지 채우지 않는다 — 상해 금액이 질병으로 새던 경로."""
    entries = _by_name(["보험기간 중 상해로 1-5종 수술분류표Ⅱ에서 정한 5종 수술을 받은 경우 1천만원"])
    assert entries == {"N종수술비(상해 5종)": 10_000_000}


def test_bracket_form_in_coverage_list_is_recognized():
    """★가입담보리스트 표기(`수술비Ⅱ(1-5종)[상해3종]`)도 tier로 인정한다."""
    entries = _by_name(["289 갱신형 수술비Ⅱ(1-5종)[상해3종] 1백만원 180 20년 / 20년"])
    assert entries == {"N종수술비(상해 3종)": 1_000_000}


def test_ambiguous_line_still_fills_both_kinds():
    """★종별이 안 적힌 줄은 기존대로 양쪽에 넣는다(기존 동작 보존 — 이번 수정 범위 밖)."""
    entries = _by_name(["기타 3종 수술을 받은 경우 50만원"])
    assert entries == {"N종수술비(상해 3종)": 500_000, "N종수술비(질병 3종)": 500_000}
